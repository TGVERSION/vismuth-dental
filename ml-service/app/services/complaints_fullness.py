import json
from langchain_core.messages import SystemMessage, HumanMessage
from .llm_setup import llm_fullness

async def get_complaints_fullness(example_prompt: str) -> dict:
    system_prompt = """
Ты — ассистент врача. Твоя задача — проверить текст врача в поле «Жалобы» на соответствие критериям полноты.

Критерии полноты:
1. Локализация (сторона, область)
2. Характер (тупая, жжение, колющая)
3. Интенсивность (0-10 или словами)
4. Связь с факторами (провокация/облегчение)
5. Сопутствующие симптомы (тошнота, слабость и др.)

Особые случаи:
Если текст означает "жалоб нет" ("жалоб нет", "жалобы отсутствуют") или это медицинский осмотр без жалоб ("осмотр", "диспансеризация") - верни status full, color green, analysis и suggested_text пустые строки.

Подсчет критериев (если есть жалобы):
5 критериев - status full, color green
3-4 критерия - status incomplete, color yellow
0-2 критерия - status incomplete, color red

Для status incomplete:
Сохрани введенный врачом текст. Добавь маркеры [...] для недостающих данных. 
Если текст из одного слова или неинформативен - создай шаблон с нуля. Не пиши клинические выводы.

Формат ответа (строго JSON без дополнительных комментариев):
{
"status": "full" | "incomplete",
"color": "green" | "yellow" | "red",
"analysis": "Краткое описание недостающих критериев и их количество (только при incomplete, иначе пусто)",
"suggested_text": "Сгенерированный шаблон с маркерами [...] (только при incomplete, иначе пусто)"
}

Примеры:

Вход: "Жалоб нет"
Ответ: {
"status":"full",
"color":"green",
"analysis":"",
"suggested_text":""}

Вход: "Пациент жалуется на давящую боль за грудиной с иррадиацией в левое плечо, интенсивность 5/10, возникает при быстрой ходьбе, проходит в покое через 2-3 минуты. Тошноты, головокружения нет."
Ответ:
{
"status": "full",
"color": "green",
"analysis": "",
"suggested_text": ""
}

Вход: "Сильно болит голова и подташнивает."
Ответ:
{
"status": "incomplete",
"color": "yellow",
"analysis": "Отсутствуют: точная локализация боли, характер боли, оценка интенсивности, связь с факторами.",
"suggested_text": "Жалобы на [характер боли] головную боль в области [локализация], интенсивностью [0-10]. Боль провоцируется [фактор], облегчается [фактор]. Сопровождается тошнотой. [Указать сопутствующие симптомы или их отсутствие]."
}

Вход: "Болит"
Ответ: {
"status":"incomplete",
"color":"red",
"analysis":"1 критерий из 5",
"suggested_text":"Боль в [локализация], [характер], интенсивность [0-10]. Провоцирует [фактор], облегчает [фактор]. Сопутствующие симптомы: [...]"
}

Текст врача для анализа:
"""
    
    messages = [
        SystemMessage(content=system_prompt),
        HumanMessage(content=example_prompt)
    ]
    
    response = await llm_fullness.ainvoke(messages)
    result = json.loads(response.content)
    
    return result