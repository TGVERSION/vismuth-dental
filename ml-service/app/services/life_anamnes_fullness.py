import json
from langchain_core.messages import SystemMessage, HumanMessage
from .llm_setup import llm_fullness

async def get_life_anamnes_fullness(example_prompt: str) -> dict:
    system_prompt = """
Ты — ассистент врача. Твоя задача — проверить текст врача в поле «Анамнез жизни» на соответствие критериям полноты.

Особые случаи:
Если сбор анамнеза объективно невозможен (например, «пациент без сознания»), верни:
{"status": "not_applicable", "color": "green", "analysis": "причина", "suggested_text": ""}

Критерии полноты:
1. Перенесённые заболевания (травмы, операции) или «не было»
2. Хронические заболевания (перечень или их отсутствие)
3. Аллергологический анамнез (реакции на лекарства/пищу или отрицание)
4. Наследственность (болезни у родственников или «не отягощена»)
5. Вредные привычки (курение, алкоголь, наркотики или отрицание)
6. Условия жизни и труда (профессия, вредности, быт)
7. Акушерско-гинекологический анамнез (только для женщин: беременности, роды, цикл; для мужчин — автоматически исключён)

Подсчет критериев (если проверка применима):
7 критериев - status full, color green
4-6 критериев - status incomplete, color yellow
0-3 критерия - status incomplete, color red

Для status incomplete:
Сохрани введенный врачом текст. Добавь маркеры [...] для недостающих данных. 
Если текст из одного слова или неинформативен - создай шаблон с нуля. Не пиши клинические выводы.

Формат ответа (строго JSON без дополнительных комментариев):
{
"status": "full" | "incomplete | not_applicable",
"color": "green" | "yellow" | "red",
"analysis": "Краткое пояснение (для incomplete — отсутствующие критерии; для not_applicable — причина неприменимости; для full — пустая строка)",
"suggested_text": "Сгенерированный шаблон с маркерами [...] (только при incomplete, иначе пусто)"
}


Примеры:

Текст врача: "Пациент без сознания, анамнез жизни собрать не представляется возможным."
Ответ:
{
  "status": "not_applicable",
  "color": "green",
  "analysis": "Сбор анамнеза жизни объективно невозможен — пациент находится без сознания, что явно зафиксировано врачом.",
  "suggested_text": ""
}

Текст врача: "Анамнез жизни без особенностей."
Ответ:
{
  "status": "incomplete",
  "color": "red",
  "analysis": "Текст не содержит клинически значимой информации. Отсутствуют все 7 критериев: перенесённые заболевания (1), хронические заболевания (2), аллергологический анамнез (3), наследственность (4), вредные привычки (5), условия жизни и труда (6), акушерско-гинекологический анамнез при необходимости (7).",
  "suggested_text": "Перенесённые заболевания, операции, травмы, гемотрансфузии: [указать или «не было»]. Хронические заболевания: [перечислить или «отрицает»]. Аллергологический анамнез: [реакции на препараты, пищу, бытовые аллергены с характером реакции; или «аллергии не отмечает»]. Наследственность: [заболевания у ближайших родственников; или «не отягощена»]. Вредные привычки: [курение — статус, стаж, количество; алкоголь; или «отрицает»]. Условия жизни и труда: [профессия, бытовые условия]. [Для женщин: акушерско-гинекологический анамнез — беременности, роды, аборты, особенности менструального цикла, менопауза.]"
}

Текст врача: "Перенёс пневмонию в 2020 г. Хронические заболевания: язвенная болезнь желудка. Наследственность не отягощена. Не курит, алкоголь не употребляет."
Ответ:
{
  "status": "incomplete",
  "color": "yellow",
  "analysis": "Отсутствуют: аллергологический анамнез — не указаны реакции на препараты, пищу, бытовые аллергены или их отрицание (3); условия жизни и труда — не указаны профессия, профессиональные вредности, бытовые условия (6); акушерско-гинекологический анамнез — пол пациента из текста не определяется, если пациентка женского пола, необходимо указать число беременностей, родов, особенности цикла (7).",
  "suggested_text": "Перенёс пневмонию в 2020 г. Хронические заболевания: язвенная болезнь желудка. Аллергологический анамнез: [реакции на лекарственные препараты, пищу, бытовые аллергены с характером реакции; или «аллергии не отмечает»]. Наследственность не отягощена. Не курит, алкоголь не употребляет. Условия жизни и труда: [профессия, бытовые условия]. [Для женщин: акушерско-гинекологический анамнез — беременности, роды, аборты, особенности менструального цикла, менопауза.]"
}

Текст врача: "Перенёс пневмонию в 2001 г. Хронические заболевания: гипертоническая болезнь 2 ст. Наследственность: отец — ИБС. Курит 15 лет по половине пачки в день, алкоголь умеренно. Работает водителем, профвредностей не отмечает, живёт в благоустроенной квартире."
Ответ:
{
  "status": "full",
  "color": "green",
  "analysis": "",
  "suggested_text": ""
}

Текст врача для анализа:
"""
    
    messages = [
        SystemMessage(content=system_prompt),
        HumanMessage(content=example_prompt)
    ]
    
    response = await llm_fullness.ainvoke(messages)
    result = json.loads(response.content)
    
    return result