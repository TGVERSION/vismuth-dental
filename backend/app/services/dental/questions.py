def _detail(key: str, title: str, question: str, options, **kwargs) -> Group:
    return Group(key=key, title=title.capitalize(), question=question,
                 options=_opts(*options), **kwargs)


def _note(key: str, title: str, question: str, placeholder: str) -> Group:
    """Уточнение без вариантов: пациент пишет сам, может и не писать."""
    return _detail(key, title, question, (), text_placeholder=placeholder,
                   text_show="always")


def _item(value: str, label: str, form: FormRow, *groups: Group, hint: str = "") -> HealthItem:
    return HealthItem(value, label, hint, groups, form)


