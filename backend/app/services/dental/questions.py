def is_uncertain_choice(label: str) -> bool:
    """Не предлагать незнание кнопкой; свободный ответ и старые данные допустимы."""
    normalized = label.casefold().replace("ё", "е")
    return any(phrase in normalized for phrase in ("не знаю", "не помню"))


@dataclass(frozen=True)
class Option:
    value: str
    label: str


@dataclass(frozen=True)
class Group:
    """Группа кнопок на экране; у группы может быть поле для своего текста.

    `text_required` — текст нужен всегда; если поле есть и выбрано «Другое»,
    текст нужен тоже. `text_show` — когда экран показывает поле: всегда,
    после выбора любого варианта или только при «Другое».
    """

    key: str
    question: str
    options: tuple[Option, ...] = ()
    multiple: bool = True
    text_placeholder: str | None = None
    text_required: bool = False
    text_show: Literal["always", "on_select", "on_other"] = "on_select"
    selection_required: bool = False
    title: str | None = None


@dataclass(frozen=True)
class FormRow:
    """Строка бланка: номер, формулировка бланка и что в ней вписывается.

    `has_answer` — у строки свой «Да / Нет» (у «Получали ли Вы:» и
    «Для женщин:» его нет, есть только у подпунктов). `subs` — подпункты:
    вариант группы `sub_group` и его формулировка в бланке. `underline` —
    варианты «нужное подчеркнуть» из группы `underline_group`. `note` —
    подпись к вписанному тексту: «Если да, то когда …».
    """

    number: int
    text: str
    note: str | None = None
    has_answer: bool = True
    sub_group: str | None = None
    subs: tuple[tuple[str, str], ...] = ()
    underline_group: str | None = None
    underline: tuple[tuple[str, str], ...] = ()


@dataclass(frozen=True)
class HealthItem:
    value: str
    label: str
    hint: str
    detail_groups: tuple[Group, ...]
    form: FormRow


def _opts(*pairs: tuple[str, str]) -> tuple[Option, ...]:
    return tuple(Option(value, label) for value, label in pairs)


